"""
scripts/build_rookie_baseline.py — Rebuild the rookie regression model
=========================================================================
One-time (periodic) offline build: fetches historical draft/combine/
rookie-season data for the 3 most recently completed draft classes, fits
the two-stage pick-curve + combine-residual model (see rookie_baseline.py
and
docs/superpowers/specs/2026-10-04-rookie-baseline-combine-regression-design.md),
runs leave-one-class-out cross-validation, prints the per-category report,
and writes the fitted coefficients to rookie_baseline_fitted.py.

Run this again after a new draft class completes its rookie season --
update TRAINING_DRAFT_YEARS below to roll the 3-class window forward
(e.g. once 2026 rookies have played a season: ["2024", "2025", "2026"]).
Same "regenerate, don't hand-edit" convention as scripts/build_draft_board.py.

Run: python scripts/build_rookie_baseline.py
"""

import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from data import fetch_combine_stats, fetch_draft_history, fetch_rookie_season_stats
from identity import canonical_player_key
from rookie_baseline import (
    CATEGORIES,
    LAMBDA_GRID,
    extract_combine_features,
    fit_stage1_curve,
    fit_stage2_ridge,
    run_leave_one_class_out_cv,
)

TRAINING_DRAFT_YEARS = ["2023", "2024", "2025"]
REPO_ROOT = Path(__file__).resolve().parent.parent
FITTED_OUTPUT_PATH = REPO_ROOT / "rookie_baseline_fitted.py"

MIN_ROWS_PER_CLASS = 40  # real run produced 53-55/class; 40 is a safety margin, not a tight bound


def _assert_all_finite(value, path: str) -> None:
    """Recursively assert every numeric leaf in a fitted-model dict/list is
    finite -- a NaN or inf anywhere (e.g. from a degenerate input row) must
    fail loudly here, not silently ship inside rookie_baseline_fitted.py."""
    if isinstance(value, dict):
        for k, v in value.items():
            _assert_all_finite(v, f"{path}.{k}")
    elif isinstance(value, (list, tuple)):
        for i, v in enumerate(value):
            _assert_all_finite(v, f"{path}[{i}]")
    elif isinstance(value, (int, float)):
        if not math.isfinite(value):
            raise ValueError(f"Non-finite value at {path}: {value!r}")


def build_training_rows(draft_year: str, draft_history: dict, combine_stats: dict,
                        rookie_season_stats: dict) -> list[dict]:
    rows = []
    for name, info in draft_history.items():
        if info["draft_year"] != draft_year:
            continue
        key = canonical_player_key(name)
        actual = rookie_season_stats.get(key)
        if actual is None:
            continue
        raw_combine = combine_stats.get(key)
        combine_features = extract_combine_features(raw_combine) if raw_combine is not None else None
        rows.append({
            "player_name": name,
            "overall_pick": info["overall_pick"],
            "actual": actual,
            "combine_features": combine_features,
        })
    return rows


def write_fitted_model(fitted_model: dict) -> None:
    lines = [
        '"""',
        "rookie_baseline_fitted.py -- AUTO-GENERATED by scripts/build_rookie_baseline.py",
        "=" * 78,
        "Do not hand-edit -- regenerate by running that script after a new draft",
        "class completes its rookie season. See",
        "docs/superpowers/specs/2026-10-04-rookie-baseline-combine-regression-design.md",
        "for the model this encodes.",
        '"""',
        "",
        f"FITTED_MODEL = {fitted_model!r}",
        "",
    ]
    FITTED_OUTPUT_PATH.write_text("\n".join(lines))


def main() -> None:
    print(f"Building rookie baseline from draft classes: {TRAINING_DRAFT_YEARS}")

    all_draft_history = fetch_draft_history(
        draft_years=TRAINING_DRAFT_YEARS, cache_file=str(REPO_ROOT / "draft_history_training_cache.pkl"),
    )
    combine_stats = fetch_combine_stats(cache_file=str(REPO_ROOT / "combine_stats_cache.pkl"))
    rookie_season_stats = fetch_rookie_season_stats(
        draft_history=all_draft_history, cache_file=str(REPO_ROOT / "rookie_season_stats_cache.pkl"),
    )

    rows_by_class = {
        year: build_training_rows(year, all_draft_history, combine_stats, rookie_season_stats)
        for year in TRAINING_DRAFT_YEARS
    }
    for year, rows in rows_by_class.items():
        with_combine = sum(1 for r in rows if r["combine_features"] is not None)
        print(f"   {year}: {len(rows)} rookies with a real rookie-season row ({with_combine} with complete combine data)")

    print("\nLeave-one-class-out cross-validation (per category):")
    cv_report = run_leave_one_class_out_cv(rows_by_class, LAMBDA_GRID)
    print(f"{'Category':<8} {'Stage1 MAE':>12} {'Best combined MAE':>20} {'Stage2 included?':>18} {'lambda':>8}")
    for category in CATEGORIES:
        r = cv_report[category]
        combined = f"{r['best_combined_mae']:.3f}" if r["best_combined_mae"] is not None else "n/a"
        lam = f"{r['chosen_lambda']:.0f}" if r["chosen_lambda"] is not None else "-"
        print(f"{category:<8} {r['stage1_only_mae']:>12.3f} {combined:>20} {str(r['stage2_included']):>18} {lam:>8}")

    all_rows = [r for rows in rows_by_class.values() for r in rows]
    final_stage1 = fit_stage1_curve(all_rows)
    final_stage2: dict = {}
    for category in CATEGORIES:
        if not cv_report[category]["stage2_included"]:
            continue
        lam = cv_report[category]["chosen_lambda"]
        stage2_for_lambda = fit_stage2_ridge(all_rows, final_stage1, lam)
        if category in stage2_for_lambda:
            final_stage2[category] = stage2_for_lambda[category]

    for year, rows in rows_by_class.items():
        if len(rows) < MIN_ROWS_PER_CLASS:
            raise AssertionError(
                f"Draft class {year} has only {len(rows)} rookie-season rows "
                f"(< {MIN_ROWS_PER_CLASS}) -- likely a fetch failure or rate-limit "
                f"storm losing most of the class. Refusing to commit a degraded model."
            )
    _assert_all_finite(final_stage1, "stage1")
    _assert_all_finite(final_stage2, "stage2")

    fitted_model = {"categories": CATEGORIES, "stage1": final_stage1, "stage2": final_stage2}
    write_fitted_model(fitted_model)
    print(f"\nWrote {FITTED_OUTPUT_PATH}")
    print(f"Stage 2 included for: {sorted(final_stage2.keys())}")


if __name__ == "__main__":
    main()
